// Builds out/renderer/token-usage-panel.js from the shared dashboard sources:
//   web/style.css    → scoped under #zcode-tu-root (never touches ZCode's own DOM)
//   web/template.html→ panel body markup
//   web/app.js       → dashboard logic, evaluated per render
//   payload/panel-shell.js + payload/panel.css → icon, hover behaviour, panel chrome
// Run standalone to inspect the artifact: node tools/build-panel.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const WEB = join(here, '..', 'token-usage', 'skills', 'token-usage', 'web');
const ROOT_SEL = '#zcode-tu-root';

// Prefix every selector so the stylesheet is inert outside our subtree. The
// dashboard stylesheet is authored flat (no @media / nesting), which keeps this
// transformation trivially safe.
export function scopeCss(raw) {
  const css = raw.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\n{3,}/g, '\n\n');
  const out = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  let consumed = 0;
  while ((m = re.exec(css))) {
    const prelude = m[1];
    const body = m[2];
    consumed = re.lastIndex;
    const trimmed = prelude.trim();
    if (!trimmed || trimmed.startsWith('@')) {
      out.push(`${prelude}{${body}}`);
      continue;
    }
    const selectors = trimmed.split(',').map((s) => {
      const sel = s.trim();
      if (sel === ':root' || sel === 'html' || sel === 'body') return ROOT_SEL;
      if (sel === '*') return `${ROOT_SEL}, ${ROOT_SEL} *`;
      return `${ROOT_SEL} ${sel}`;
    });
    out.push(`${selectors.join(', ')}{${body}}`);
  }
  const tail = css.slice(consumed).trim();
  if (tail) out.push(tail);
  return out.join('\n');
}

// Every selector emitted by scopeCss must be anchored to our own subtree.
export function unscopedSelectors(css) {
  const bad = [];
  const re = /([^{}]+)\{/g;
  let m;
  while ((m = re.exec(css))) {
    for (const sel of m[1].split(',')) {
      const s = sel.trim();
      if (!s || s.startsWith('@')) continue;
      if (s.startsWith(ROOT_SEL) || s.startsWith('button[data-zcode-token-usage')) continue;
      if (s.includes(` ${ROOT_SEL}`)) continue;
      bad.push(s);
    }
  }
  return bad;
}

export function buildPanelSource() {
  const styleCss = readFileSync(join(WEB, 'style.css'), 'utf8');
  const template = readFileSync(join(WEB, 'template.html'), 'utf8');
  const appJs = readFileSync(join(WEB, 'app.js'), 'utf8');
  const shell = readFileSync(join(here, 'payload', 'panel-shell.js'), 'utf8');
  const panelCss = readFileSync(join(here, 'payload', 'panel.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

  const bodyStart = template.indexOf('<body>');
  const bodyEnd = template.lastIndexOf('</body>');
  if (bodyStart < 0 || bodyEnd < 0) throw new Error('build-panel: template.html 缺少 <body>');
  const html = template
    .slice(bodyStart + '<body>'.length, bodyEnd)
    .replace(/<!--\s*__APP__\s*-->/, '')
    .trim();

  const css = `${scopeCss(styleCss)}\n${panelCss}`;
  const out = shell
    .replace('/*__CSS__*/', () => JSON.stringify(css))
    .replace('/*__HTML__*/', () => JSON.stringify(html))
    .replace('/*__APP__*/', () => JSON.stringify(appJs));
  if (out === shell) throw new Error('build-panel: 占位符未被替换');
  return `// generated by tools/build-panel.mjs — do not edit by hand\n${out}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const src = buildPanelSource();
  const out = join(here, 'build');
  mkdirSync(out, { recursive: true });
  const file = join(out, 'token-usage-panel.js');
  writeFileSync(file, src);
  console.log(`built ${file} (${(src.length / 1024).toFixed(1)} KB)`);

  const css = JSON.parse(src.match(/const CSS = ("(?:[^"\\]|\\.)*");/)[1]);
  const bad = unscopedSelectors(css);
  console.log(bad.length ? `未加作用域的选择器: ${bad.slice(0, 8).join(' | ')}` : '全部选择器已限定在 #zcode-tu-root 内');
}
